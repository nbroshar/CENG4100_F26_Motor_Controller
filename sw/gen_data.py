#!/usr/bin/env python3
"""gen_data.py -- golden data for Case 1 (motor controller).

Runs the customer's PI speed controller in exact integer arithmetic against a
simple motor model, and writes data.h: the setpoint and measured-speed inputs
for every pass, and the duty cycle the controller must output for each.
Any firmware rewrite must reproduce these outputs exactly.

You do not need to run this; data.h is already generated. Run it only if the
instructor changes the gains or the test length:  python gen_data.py
"""

from pathlib import Path

N_PASSES = 1000
KP, KI, ILIM = 300, 12, 1 << 18      # gains (Q8) and integrator limit
PWM_PERIOD = 1000                    # duty cycle range 0..1000
SETPOINTS = [0, 1500, 3000, 4000, 800, 2500, 3500, 1000]   # 12-bit speed units


def lcg(state):
    state = (state * 1103515245 + 12345) & 0x7FFFFFFF
    return state, state


def main():
    sp_list, meas_list, duty_list = [], [], []
    integ, speed, seed = 0, 0, 2026
    for i in range(N_PASSES):
        sp = SETPOINTS[(i // 125) % len(SETPOINTS)]
        seed, r = lcg(seed)
        noise = (r >> 16) % 17 - 8                     # -8 .. +8
        meas = max(0, min(4095, speed + noise))

        # The controller, exactly as firmware.c computes it (>> is floor).
        err = sp - meas
        p = KP * err
        integ = max(-ILIM, min(ILIM, integ + KI * err))
        duty = max(0, min(PWM_PERIOD, (p + integ) >> 8))

        sp_list.append(sp)
        meas_list.append(meas)
        duty_list.append(duty)
        speed += (duty * 4 - speed) >> 3                # motor responds to duty

    def arr(ctype, name, values):
        rows = [", ".join(str(v) for v in values[i:i + 16]) for i in range(0, len(values), 16)]
        return f"static const {ctype} {name}[N_PASSES] = {{\n    " + ",\n    ".join(rows) + "\n};\n"

    out = Path(__file__).with_name("data.h")
    out.write_text(
        "/* data.h -- generated by gen_data.py. Do not edit. */\n"
        "#ifndef CASE1_DATA_H\n#define CASE1_DATA_H\n#include <stdint.h>\n\n"
        f"#define N_PASSES   {N_PASSES}\n#define PWM_RANGE  {PWM_PERIOD}\n"
        f"#define GAIN_KP    {KP}\n#define GAIN_KI    {KI}\n#define INTEG_LIM  {ILIM}\n\n"
        + arr("int16_t", "setpoint", sp_list) + "\n"
        + arr("int16_t", "measured", meas_list) + "\n"
        + arr("uint16_t", "expected_duty", duty_list)
        + "\n#endif\n")
    clamped = sum(1 for d in duty_list if d in (0, PWM_PERIOD))
    print(f"wrote {out}: {N_PASSES} passes, {clamped} with the output clamped")


if __name__ == "__main__":
    main()
